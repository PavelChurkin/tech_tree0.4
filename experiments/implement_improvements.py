def load_json(filename: str) -> Dict[str, List[Dict[str, Any]]]:
    """Load JSON file with UTF-8 encoding."""
    with open(filename, 'r', encoding='utf-8') as f:
        return json.load(f)

def save_json(filename: str, data: Dict[str, List[Dict[str, Any]]]):
    """Save JSON file with UTF-8 encoding and proper formatting."""
    with open(filename, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def find_tech(technologies: List[Dict], name: str) -> Dict | None:
    """Find technology by name."""
    for tech in technologies:
        if tech['название'] == name:
            return tech
    return None

def tech_exists(technologies: List[Dict], name: str) -> bool:
    """Check if technology exists."""
    return find_tech(technologies, name) is not None

def add_technology(technologies: List[Dict], название: str, описание: str, условия: Any):
    """Add technology if it doesn't exist."""
    if not tech_exists(technologies, название):
        technologies.append({
            "название": название,
            "описание": описание,
            "условия": условия
        })
        print(f"✓ Added: {название}")
        return True
    else:
        print(f"  Skipped (exists): {название}")
        return False

def update_tech_dependencies(technologies: List[Dict], название: str, new_условия: Any):
    """Update dependencies of existing technology."""
    tech = find_tech(technologies, название)
    if tech:
        tech['условия'] = new_условия
        print(f"✓ Updated dependencies: {название}")
        return True
    else:
        print(f"  Not found: {название}")
        return False

